const BOARD_W = 16
const keysJson = layoutJson.keys
if (keysJson.length !== 84) fail(`layout.json has ${keysJson.length} keys`)
const ids = KEY_ROWS.flat()
const codeOf = new Map(codes.map((c) => [c.value, c]))

const keys = keysJson.map((k, i) => {
  if (k.id !== i + 1) fail(`layout.json key ${i} has id ${k.id}`)
  if (k.y !== k.row - 1) fail(`key ${k.id}: y ${k.y} != row - 1`)
  if (KEY_ROWS[k.row - 1].indexOf(ids[i]) < 0) fail(`key ${k.id} (${ids[i]}) is not in row ${k.row}`)
  const label = LEGENDS[k.label] ?? k.label
  const fnDef = k.default.L1
  let sub
  if (fnDef.mode !== 0) {
    const c = codeOf.get(fnDef.hwcode)
    sub = c ? c.short : hex2(fnDef.hwcode)
    if (sub === label) sub = undefined
  }
  return { id: ids[i], no: k.id, label, sub, x: k.x, y: k.y, w: k.w, row: k.row }
})

KEY_ROWS.forEach((rowIds, r) => {
  const row = keys.filter((k) => k.row === r + 1)
  if (row.map((k) => k.id).join(' ') !== rowIds.join(' ')) fail(`row ${r + 1} ids do not match layout.json`)
  let x = 0
  for (const k of row) {
    if (Math.abs(k.x - x) > 1e-9) fail(`key ${k.id}: x ${k.x}, expected ${x}`)
    x += k.w
  }
  if (Math.abs(x - BOARD_W) > 1e-9) fail(`row ${r + 1} spans ${x}u`)
})

/** Wire codes of a factory default: mode 0 -> [] (empty), double click -> [130, 130]. */
function factoryWire(def) {
  if (def.mode === 0) return []
  if (def.mode === 6 && def.hwcode === 199) return [130, 130]
  if (!Number.isInteger(def.hwcode) || def.hwcode < 1 || def.hwcode > 255) fail(`bad factory hwcode ${def.hwcode}`)
  return [def.hwcode]
}

const keyLine = (k) =>
  `  { id: ${q(k.id)}, no: ${k.no}, label: ${q(k.label)}${k.sub !== undefined ? `, sub: ${q(k.sub)}` : ''}, ` +
  `x: ${k.x}, y: ${k.y}, w: ${k.w}, row: ${k.row} },`

function wireRows(level) {
  const items = keysJson.map((k) => `[${factoryWire(k.default[level]).join(', ')}]`)
  const lines = []
  for (let i = 0; i < items.length; i += 16) lines.push(`    ${items.slice(i, i + 16).join(', ')},`)
  return lines.join('\n')
}

