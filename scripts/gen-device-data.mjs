function deriveNames(c) {
  const w = c.webCode ?? ''
  let m
  if ((m = /^Key([A-Z])$/.exec(w)) || (m = /^Digit(\d)$/.exec(w)) || (m = /^(F\d{1,2})$/.exec(w))) return [m[1], m[1], m[1]]
  if ((m = /^Numpad(\d)$/.exec(w))) return [`N${m[1]}`, `小键盘 ${m[1]}`, `Numpad ${m[1]}`]
  if (c.category === 'special') {
    const h = hex2(c.code)
    const where = c.deviceDefaultOn.length ? ` (factory ${c.deviceDefaultOn.join(', ')})` : ''
    return [h, `设备功能 ${h}`, `Device function ${h}`, `Unknown device function, preserved${where}`]
  }
  return null
}

const codes = codesJson
  .filter((c) => c.code !== 0)
  .map((c) => {
    const id = c.webCode ?? EXTRA_IDS[c.code] ?? fail(`no id for code ${c.code}`)
    const [short, zh, en, note] = NAMES[c.code] ?? deriveNames(c) ?? fail(`no names for code ${c.code}`)
    if ([...short].length > 6) fail(`short "${short}" of code ${c.code} is longer than 6 characters`)
    const wire = c.code === 199 ? [130, 130] : [c.code]
    if (JSON.stringify(wire) !== JSON.stringify(c.wire)) fail(`wire mismatch for code ${c.code}`)
    const proLabel = c.labelRoundTrips && c.proLabel ? c.proLabel : null
    const pickable = (c.category === 'key' && proLabel !== null) || c.uiItemId != null
    return { value: c.code, id, category: c.category, wire, short, zh, en, proLabel, kb84Mode: c.mode, note, pickable }
  })

{
  const ids = new Set(codes.map((c) => c.id.toLowerCase()))
  if (ids.size !== codes.length) fail('code ids are not unique (case-insensitively)')
  for (const c of codes) {
    // codeForKeyboardEventCode relies on: an id is a KeyboardEvent.code name exactly for key/media/power codes.
    const hasWebCode = codesJson.find((x) => x.code === c.value).webCode != null
    if (hasWebCode !== ['key', 'media', 'power'].includes(c.category)) fail(`webCode/category mismatch for ${c.value}`)
  }
}

